"""Buyer clean-up and segments for importer lists (Canada now, UK next). Name-based rules; extend the lists as
users flag mistakes.

classify(name) → None (not a buyer: courier, broker, marketplace…) or one of:
  "specialist"  name says gift, craft, stationery, books, decor, import/wholesale… (shown first)
  "other"       nothing in the name tells us
  "chain"       big retail chain: real buyer, hard for a small exporter (shown lower, tagged)
  "luxury"      luxury house that mostly sources in-house (shown last, tagged)
"""
import re

NOT_BUYER = re.compile(
    r"\b(DHL|FEDEX|FED EX|UPS|TNT|PUROLATOR|CANPAR|PARCEL\w*|ROYAL MAIL|DPD|EVRI|HERMES PARCEL|ARAMEX|YODEL|"
    r"LIVINGSTON|CLEARIT|CUSTOMS|BROKER\w*|FREIGHT|LOGISTIC\w*|FORWARD\w*|SHIPPING|CARGO|COURIER\w*|"
    r"AMAZON|EBAY|ALIBABA|FULFIL\w*|WAREHOUS\w*|TRANSPORT\w*|HAULAGE|AIRWAYS|AIRLINES?|"
    r"CLEARANCE|DISTRIBUTION SERVICES|EXPRESS (CANADA|LTD|LIMITED|INC))\b", re.I)

LUXURY = re.compile(
    r"\b(LOUIS VUITTON|CHRISTIAN DIOR|DIOR|BURBERRY|GOYARD|RICHEMONT|CHANEL|GUCCI|PRADA|HERMES|CARTIER|ROLEX|"
    r"TIFFANY|RIMOWA|MONTBLANC|BOTTEGA|BALENCIAGA|SAINT LAURENT|CELINE|FENDI|LOEWE|VALENTINO|VERSACE|"
    r"SALVATORE FERRAGAMO|FERRAGAMO|MULBERRY|ASPINAL|SMYTHSON|TOD'?S|BVLGARI|BULGARI|VAN CLEEF|GRAFF|"
    r"PATEK|OMEGA|LVMH|KERING|MICHAEL KORS|COACH|RALPH LAUREN|HUGO BOSS|ARMANI)\b", re.I)

CHAIN = re.compile(
    r"\b(WAL-?MART|COSTCO|CANADIAN TIRE|WINNERS|HOMESENSE|MARSHALLS|TJX|T\.?K\.? MAXX|LOBLAW\w*|SOBEYS|"
    r"METRO INC|DOLLARAMA|GIANT TIGER|HUDSON'?S BAY|SIMONS|IKEA|BEST BUY|STAPLES|HOME DEPOT|LOWE'?S|RONA|"
    r"SHOPPERS DRUG|LONDON DRUGS|INDIGO BOOKS|PET VALU|SPORT CHEK|"
    r"TESCO|SAINSBURY'?S?|ASDA|MORRISONS?|B ?& ?M RETAIL|POUNDLAND|T ?J MORRIS|NEXT RETAIL|MARKS (AND|&) SPENCER|"
    r"JOHN LEWIS|ARGOS|WILKO|PRIMARK|HOME BARGAINS|THE RANGE|DUNELM|HARRODS|SELFRIDGES|LIBERTY RETAIL|"
    r"W ?H ?SMITH|RYMAN|PAPERCHASE|BOOTS|SUPERDRUG|LIDL|ALDI|ROSS STORES|TARGET|KOHL'?S|MACY'?S|NORDSTROM)\b", re.I)

SPECIALIST = re.compile(
    r"(GIFT|CRAFT|HANDICRAFT|ARTISAN|STATIONER|PAPER|BOOK|ART SUPPL|DECOR|HOME|INTERIOR|IMPORT|WHOLESALE|TRADING|"
    r"DISTRIBUT|BOUTIQUE|DESIGN|LEATHER|TEXTILE|FABRIC|LINEN|RUG|CARPET|JEWEL|BEAD|SPICE|FOODS?|TEA|COFFEE|"
    r"FURNITURE|POTTERY|CERAMIC|CANDLE|INCENSE|HERBAL|AYURVED|ORGANIC|FASHION|APPAREL|CLOTHING|SAREE|SARI|"
    r"BAZAAR|EMPORIUM|COLLECTION|PROMOTION|MERCHANDIS|INDIA|INDIAN|ASIAN|ORIENTAL|ETHNIC)", re.I)


def classify(name):
    n = name or ""
    if NOT_BUYER.search(n):
        return None
    if LUXURY.search(n):
        return "luxury"
    if CHAIN.search(n):
        return "chain"
    if SPECIALIST.search(n):
        return "specialist"
    return "other"


SEGMENT_RANK = {"specialist": 3, "other": 2, "chain": 1, "luxury": 0}
